import { Link, createFileRoute } from "@tanstack/react-router";
import { useState } from "react";
import { Bell } from "lucide-react";
import { notifications as notificationsApi } from "@/services/api/notifications";
import { demoNotifications } from "@/services/demo/dataset";
import { usePvQuery } from "@/lib/data-source";
import { useRole } from "@/lib/auth";
import { useQueryClient } from "@tanstack/react-query";
import { Button } from "@/components/ui/button";
import {
  EmptyState,
  PageHeader,
  Pager,
  QueryBoundary,
  paginate,
  Section,
  SourceTag,
  StatusPill,
  type Tone,
} from "@/components/pv/primitives";
import type { Notification } from "@/types/pv";

export const Route = createFileRoute("/_app/notifications")({
  head: () => ({
    meta: [
      { title: "Notifications — MedNova PV Assist" },
      {
        name: "description",
        content:
          "Case assignments, seriousness flags, overdue follow-ups, coding and review requests.",
      },
      { property: "og:title", content: "Notifications — MedNova PV Assist" },
      {
        property: "og:description",
        content: "Operational notification centre for pharmacovigilance teams.",
      },
    ],
  }),
  component: NotificationsPage,
});

const tone: Record<Notification["type"], Tone> = {
  CASE_ASSIGNED: "info",
  SERIOUSNESS_MISMATCH: "warning",
  FOLLOW_UP_DUE: "warning",
  CASE_OVERDUE: "critical",
  CODING_REQUIRED: "info",
  MANAGER_REVIEW: "info",
  SIGNAL_REVIEW: "warning",
  PSUR_COMPLETE: "success",
  LINELIST_FAILED: "critical",
  PSUR_SENT_FOR_SCIENTIFIC_REVIEW: "info",
  PSUR_RETURNED_TO_MAH: "warning",
  PSUR_AWAITING_PEER_REVIEW: "info",
  PSUR_PEER_REVIEW_COMPLETE: "success",
};

function NotificationsPage() {
  const queryClient = useQueryClient();
  const role = useRole();
  const query = usePvQuery(
    ["notifications", role],
    () => notificationsApi.list(role),
    () => demoNotifications,
  );
  const [page, setPage] = useState(1);
  const [unreadOnly, setUnreadOnly] = useState(false);
  return (
    <>
      <PageHeader
        title="Notifications"
        description="Work items generated by the platform. Opening a notification does not change any safety record."
        meta={query.data ? <SourceTag source={query.data.source} /> : null}
      />
      <div className="p-6">
        <Section
          title="All notifications"
          description="Unread first, then newest. 10 to a page."
          actions={
            <Button
              size="sm"
              variant={unreadOnly ? "default" : "outline"}
              aria-pressed={unreadOnly}
              onClick={() => {
                setUnreadOnly((v) => !v);
                setPage(1);
              }}
            >
              {unreadOnly ? "Showing unread only" : "Show unread only"}
            </Button>
          }
        >
          <QueryBoundary query={query}>
            {(all) => {
              const items = [...all]
                .filter((n) => !unreadOnly || !n.read)
                .sort((a, b) => Number(a.read) - Number(b.read) || b.at.localeCompare(a.at));
              const pageCount = Math.max(1, Math.ceil(items.length / 10));
              const shownPage = Math.min(page, pageCount);
              return items.length === 0 ? (
                <EmptyState title={unreadOnly ? "No unread notifications" : "Nothing to review"} />
              ) : (
                <div className="space-y-3">
                  <ul className="divide-y divide-border">
                    {paginate(items, shownPage).map((n) => (
                      <li key={n.id} className="flex flex-wrap items-start gap-3 py-3">
                        <Bell
                          className={
                            n.read
                              ? "mt-0.5 size-4 text-muted-foreground"
                              : "mt-0.5 size-4 text-primary"
                          }
                        />
                        <div className="min-w-0 flex-1">
                          <div className="flex flex-wrap items-center gap-2">
                            <p className="text-sm font-medium">{n.title}</p>
                            <StatusPill tone={tone[n.type]}>
                              {n.type.replaceAll("_", " ").toLowerCase()}
                            </StatusPill>
                            {!n.read ? <StatusPill tone="info">unread</StatusPill> : null}
                          </div>
                          <p className="mt-0.5 text-sm text-muted-foreground">{n.body}</p>
                        </div>
                        <span className="mono-num text-xs text-muted-foreground">
                          {n.at.replace("T", " ").slice(0, 16)} UTC
                        </span>
                        {n.link ? (
                          <Link to={n.link} className="text-sm text-primary hover:underline">
                            Open
                          </Link>
                        ) : null}
                        {!n.read ? (
                          <Button
                            variant="ghost"
                            size="sm"
                            onClick={async () => {
                              await notificationsApi.markRead(n.id);
                              await queryClient.invalidateQueries({ queryKey: ["notifications"] });
                            }}
                          >
                            Mark read
                          </Button>
                        ) : null}
                      </li>
                    ))}
                  </ul>
                  <Pager page={shownPage} total={items.length} onPageChange={setPage} />
                </div>
              );
            }}
          </QueryBoundary>
        </Section>
      </div>
    </>
  );
}
