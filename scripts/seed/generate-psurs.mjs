#!/usr/bin/env node
/**
 * SYNTHETIC screened PSURs for the test organisation (slug mednova-test-a),
 * for the "PSURs due and overdue" forecast. Writes SQL to stdout; run it in
 * the SQL editor (service role). Every product, MAH and person is invented
 * and named TEST.
 *
 *   node scripts/seed/generate-psurs.mjs [YYYY-MM-DD] > psur-seed.sql
 *
 * Dates are relative to the given day (default today) so the demo always
 * shows the same picture:
 *   - 1 OVERDUE        TEST Amlodipine / TEST Alpha Pharma (6-month cycle)
 *   - 2 DUE SOON       TEST Metformin / TEST Beta Labs (window open now)
 *                      TEST Ceftriaxone / TEST Gamma Health (officer-recorded next DLP)
 *   - 1 CANNOT FORECAST TEST Artemether / TEST Delta Medicines (interval unreadable)
 *   - 1 due later      TEST Losartan / TEST Alpha Pharma
 * 9 reports across 4 MAHs; TEST Alpha Pharma has 2 of 3 submissions late.
 */
import { buildPsurSeed } from "./psur-seed-data.mjs";

const today = process.argv[2] ? new Date(`${process.argv[2]}T00:00:00Z`) : new Date();
const docs = buildPsurSeed(today);
const iso = (d) => d.toISOString().slice(0, 10);
const q = (s) => `'${s.replace(/'/g, "''")}'`;
console.log(
  `-- Generated by scripts/seed/generate-psurs.mjs for ${iso(today)}. SYNTHETIC TEST DATA.`,
);
console.log(
  `-- Test organisation only (slug mednova-test-a). Re-running replaces these ${docs.length} rows.`,
);
for (const d of docs) {
  console.log(
    `insert into public.pv_psur_documents (id, organization_id, data)\n` +
      `select ${q(d.id)}, id, ${q(JSON.stringify(d))}::jsonb from public.organizations\n` +
      `where slug = 'mednova-test-a' and name ilike '%synthetic data only%'\n` +
      `on conflict (id) do update set data = excluded.data;`,
  );
}
